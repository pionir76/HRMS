namespace HRMS.Modules.Approval;

//--------------------------------------------------------------------------------//
// 결재 3단계(안전관리원/안전관리책임자/안전관리총괄자) 중 한 레벨이 특정 문서유형에서
// 어떻게 취급되는지. DB에 저장하는 값이 아니라, 문서유형별로 ApprovalDocuments.ModesFor에
// 고정으로 선언한다. 문서 인스턴스마다 달라지는 값이 아니라
// "이 문서유형은 원래 이렇게 결재한다"는 시스템 사양이기 때문이다.
//
// NotApplicable과 Delegated는 실제 승인 절차가 없다는 점에서 동작(순서 판정, 승인 API 차단)이
// 완전히 동일하다 — 프론트에 보여줄 표시 문구만 다르다 ("/" vs "//전결").
//--------------------------------------------------------------------------------//
public enum ApprovalLevelMode
{
    Required,       // 실제로 결재가 필요한 레벨
    NotApplicable,  // 이 문서유형엔 이 결재단계 자체가 없음 — 프론트에 "/" 표시
    Delegated       // 이 문서유형은 이 레벨을 항상 전결 처리하기로 고정됨 — 프론트에 "//전결" 표시
}
