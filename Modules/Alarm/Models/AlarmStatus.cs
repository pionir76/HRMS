namespace HRMS.Modules.Alarm.Models;

// 압축기(채널) 경보 상태. "경보확인"은 사용자 확인 기능이 시스템 사양에 없어서 뺐다 —
// 경보가 발생하면 값이 정상 범위로 돌아올 때까지 그냥 경보발생 상태를 유지한다.
// "경보해제"도 별도로 유지되는 상태가 아니라 정상복귀대기가 끝나면 바로 정상으로 간다.
// "정상"이 0번째라 별도 판정 전 기본값도 자연스럽게 정상이 된다.
public enum AlarmStatus
{
    정상,
    경보발생대기,
    경보발생,
    정상복귀대기,
    경보비활성화
}
